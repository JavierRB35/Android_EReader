package com.javierrb35.bibliotecaia.ui

import android.app.Activity
import android.content.Intent
import android.graphics.Bitmap
import android.view.View
import android.view.ViewGroup
import android.widget.LinearLayout
import android.widget.TextView
import androidx.test.ext.junit.runners.AndroidJUnit4
import androidx.test.platform.app.InstrumentationRegistry
import com.javierrb35.bibliotecaia.R
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertTrue
import org.junit.Test
import org.junit.runner.RunWith
import java.io.File
import java.io.FileOutputStream

/**
 * Visual evidence of the actual Android-rendered premium UI.
 *
 * Checks the production Activity hierarchy, not merely whether resources
 * or classes have been packaged. Screenshots are generated by an isolated
 * emulator (no personal books or user account) for UX acceptance review.
 */
@RunWith(AndroidJUnit4::class)
class PremiumVisualProofDeviceTest {
    private val instrumentation = InstrumentationRegistry.getInstrumentation()
    private val context get() = instrumentation.targetContext

    @Test fun premiumScreensHaveRealFourActionDockAndAreCapturedAsPng() {
        val main = launch(MainActivity::class.java)
        try {
            instrumentation.waitForIdleSync()

            val dock = main.findViewById<LinearLayout>(R.id.mainNavigation)
            val ids = listOf(R.id.navLibrary, R.id.navRead, R.id.btnImport, R.id.navKnowledge)
            assertNotNull("The bottom dock must exist on the real Activity", dock)
            assertEquals("The accepted dock has exactly four visible actions", 4, dock.childCount)
            assertEquals("The order Biblioteca - Leer - Importar - Conocimiento is binding",
                ids, (0 until dock.childCount).map { dock.getChildAt(it).id })
            ids.forEach { id ->
                assertTrue("Dock item $id must be visible", main.findViewById<View>(id).isShown)
            }

            val import = main.findViewById<View>(R.id.btnImport)
            val bookCount = main.findViewById<View>(R.id.txtBookCount)
            val importLocation = IntArray(2)
            val countLocation = IntArray(2)
            import.getLocationOnScreen(importLocation)
            bookCount.getLocationOnScreen(countLocation)
            assertTrue("Import must be at the very bottom, not beside the book count",
                importLocation[1] > countLocation[1] + bookCount.height)

            assertNotNull(main.findViewById<View>(R.id.recentBookCard))
            assertNotNull(main.findViewById<View>(R.id.chipShelves))
            assertNotNull(main.findViewById<View>(R.id.txtSearch))
            screenshot("biblioteca-premium-v035")
        } finally {
            instrumentation.runOnMainSync { main.finish() }
        }

        val notes = launch(KnowledgeActivity::class.java)
        try {
            instrumentation.waitForIdleSync()
            val bottom = notes.findViewById<LinearLayout>(R.id.mainNavigation)
            assertNotNull("Knowledge must also show the shared bottom dock", bottom)
            assertEquals(4, bottom.childCount)
            val allTexts = mutableListOf<String>()
            fun walk(view: View) {
                if (view is TextView) allTexts += view.text.toString()
                if (view is ViewGroup) for (i in 0 until view.childCount) walk(view.getChildAt(i))
            }
            walk(notes.window.decorView)
            assertTrue("Existing Nueva nota action must remain", "Nueva nota" in allTexts)
            assertTrue("Existing Exportar action must remain", "Exportar" in allTexts)
            screenshot("conocimiento-premium-v035")
        } finally {
            instrumentation.runOnMainSync { notes.finish() }
        }

        val settings = launch(SettingsActivity::class.java)
        try {
            instrumentation.waitForIdleSync()
            assertFalse("Settings must stay open", settings.isFinishing)
            screenshot("ajustes-premium-v035")
        } finally {
            instrumentation.runOnMainSync { settings.finish() }
        }
    }

    private fun <T : Activity> launch(type: Class<T>): T {
        val activity = instrumentation.startActivitySync(
            Intent(context, type).addFlags(Intent.FLAG_ACTIVITY_NEW_TASK or Intent.FLAG_ACTIVITY_CLEAR_TASK))
        @Suppress("UNCHECKED_CAST")
        return activity as T
    }

    private fun screenshot(name: String) {
        instrumentation.waitForIdleSync()
        val image = instrumentation.uiAutomation.takeScreenshot()
        assertNotNull("Android screenshot capture is required for visual QA", image)
        val directory = requireNotNull(context.getExternalFilesDir("premium-ui-proof")) {
            "Screenshot artifact directory unavailable"
        }
        directory.mkdirs()
        val output = File(directory, "$name.png")
        FileOutputStream(output).use { stream ->
            assertTrue("PNG screenshot export failed", image.compress(Bitmap.CompressFormat.PNG, 100, stream))
        }
        image.recycle()
        assertTrue("Screenshot is missing or empty", output.length() > 1000L)
    }
}
